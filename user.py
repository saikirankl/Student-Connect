class User:
    def __init__(self, user_name, password, name, age, stream, projectdescription, agenda, skills, current_stage):
        self.user_name = user_name
        self.password = password 
        self.name = name
        self.age = age
        self.stream = stream
        self.projectdescription = projectdescription
        self.agenda = agenda
        self.skills = skills
        self.current_stage = current_stage